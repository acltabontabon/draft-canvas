#!/usr/bin/env node
/** Generates the searchable index and lazy local path groups from the pinned Simple Icons package.
 * Run `npm run icons:generate` after updating simple-icons; `--check` verifies the committed assets.
 * The index contains no artwork. Grouping by slug initial bounds import overhead without thousands
 * of tiny chunks, and lets the service worker cache every group for offline use.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as icons from 'simple-icons';

const directory = new URL('../src/nodes/technologyCatalog/', import.meta.url);
const version = JSON.parse(readFileSync(new URL('../node_modules/simple-icons/package.json', import.meta.url), 'utf8')).version;
const catalog = Object.values(icons).sort((a, b) => a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0);
const files = new Map();
files.set('index.json', JSON.stringify({ version, icons: catalog.map(({ title, slug }) => [title, slug]) }) + '\n');
const groups = Object.groupBy(catalog, (icon) => icon.slug[0]);
for (const [key, members] of Object.entries(groups)) {
  files.set(`${key}.json`, JSON.stringify(Object.fromEntries(members.map(({ slug, path }) => [slug, path]))) + '\n');
}
files.set('loaders.ts', `// Generated by scripts/technology-catalog.mjs. Do not edit.\nexport const TECHNOLOGY_PATH_LOADERS: Readonly<Record<string, () => Promise<{ default: Record<string, string> }>>> = {\n${Object.keys(groups).sort().map((key) => `  '${key}': () => import('./${key}.json'),`).join('\n')}\n};\n`);
files.set('NOTICE.txt', [
  `Simple Icons ${version} — complete technology catalog`,
  'https://github.com/simple-icons/simple-icons',
  'Package: CC0-1.0; individual logo terms and trademarks may differ.',
  'The following source, guidelines and license information is retained from the pinned package.',
  'Artwork is distributed as separate local assets; its terms do not relicense Draft Canvas code.',
  'Paths retain the package geometry and are scaled and displayed in theme ink. No endorsement is implied.',
  '',
  ...catalog.flatMap((icon) => [
    icon.title,
    `Source: ${icon.source}`,
    ...(icon.guidelines ? [`Guidelines: ${icon.guidelines}`] : []),
    ...(icon.license ? [`License: ${icon.license.type} (${icon.license.url})`] : ['License: no individual license data supplied by Simple Icons; see source and package disclaimer.']),
    '',
  ]),
].join('\n'));

mkdirSync(directory, { recursive: true });
let stale = false;
for (const [name, content] of files) {
  const path = new URL(name, directory);
  if (process.argv.includes('--check')) {
    let existing;
    try { existing = readFileSync(path, 'utf8'); } catch { /* Missing is stale too. */ }
    if (existing !== content) { console.error(`Stale catalog asset: ${name}`); stale = true; }
  } else {
    writeFileSync(path, content);
  }
}
for (const name of readdirSync(directory)) {
  if (files.has(name)) continue;
  if (process.argv.includes('--check')) { console.error(`Obsolete catalog asset: ${name}`); stale = true; }
  else rmSync(new URL(name, directory));
}
if (stale) process.exitCode = 1;
else console.log(`${catalog.length} icons in ${Object.keys(groups).length} lazy path groups (${version}). ${fileURLToPath(directory)}`);
